import { chromium } from '@playwright/test';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport:{width:390,height:844}, deviceScaleFactor:2, isMobile:true, hasTouch:true });
const p = await ctx.newPage();
await p.goto('https://revialife.vercel.app/contact',{waitUntil:'networkidle'});
const r = await p.evaluate(()=>{
  const back = [...document.querySelectorAll('div')].find(d=>d.style.transform==='rotateY(180deg)');
  const front = back?.parentElement?.firstElementChild;
  const fb = front?.getBoundingClientRect(), bb = back?.getBoundingClientRect();
  return { frontH: fb&&Math.round(fb.height), backH: bb&&Math.round(bb.height), backScrollH: back&&back.scrollHeight, overflowY: back&&getComputedStyle(back).overflowY };
});
console.log('FLIP CARD:', JSON.stringify(r));
await p.screenshot({path:'/private/tmp/claude-501/-Users-browne/c41d6172-dd49-4568-b13b-a4548911e19e/scratchpad/shot-contact.png', fullPage:false});
